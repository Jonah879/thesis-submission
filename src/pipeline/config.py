TOPIC_INFO_CSV         = TOPIC_DIR / "topic_info.csv"

# Sentence embedding model used for both tweets and bill text.
#   all-mpnet-base-v2  — 768-dim, best quality, ~3x slower
#   all-MiniLM-L6-v2   — 384-dim, ~3-5x faster, fine for topic modelling
EMBEDDING_MODEL      = "sentence-transformers/all-mpnet-base-v2"
EMBEDDING_BATCH_SIZE = 512    # 256 is conservative; a H100 handles 512-1024
EMBEDDING_DEVICE     = None   # None -> auto-detect (cuda / mps / cpu)
EMBEDDING_FP16       = True   # halve memory + roughly double speed on CUDA

# Sanity reference for the fit: on an H100, mpnet embeds several thousand
# tweets/second. If you see single- or double-digit it/s, you are on CPU —
# get_device() will warn loudly.

# Fitting. UMAP/HDBSCAN are fit on a subsample; the rest is transformed in
# chunks. Short tweets are excluded from FITTING only — they stay retrievable.
TOPIC_FIT_SAMPLE     = 750_000
TOPIC_MIN_FIT_WORDS  = 5
TOPIC_MIN_CLUSTER_SIZE = 200
TOPIC_NR_TOPICS      = "auto"   # or an int to force reduction

# Full-corpus assignment (TopicSpace.assign) rejects a tweet below this
# similarity floor and routes it to -1 ("unclassified") instead of forcing
# it into the nearest centroid. The floor is data-driven: computed at fit
# time as this percentile of the fit pool's own similarity-to-assigned-
# centroid distribution (persisted in topic_meta.json as
# "assign_min_similarity"), not a hardcoded constant.
TOPIC_ASSIGN_MIN_SIM_PERCENTILE = 5

# Bill summaries are chunked before embedding so a long summary is not
# averaged into mush; the vote vector is the max-pooled chunk similarity.
TOPIC_SUMMARY_CHUNK_WORDS = 200
TOPIC_MAX_SUMMARY_CHUNKS  = 8

# Retrieval scoring: score = TOPIC_WEIGHT * topic_sim + EMB_WEIGHT * emb_sim
TOPIC_WEIGHT  = 0.5
EMB_WEIGHT    = 0.5
TOPIC_TOP_K   = 25     # max tweets returned per candidate
TOPIC_MIN_SIM = 0.25   # score floor; 0.0 -> pure top-K, never empty

