# ---------------------------------------------------------------------------
# Topic modelling / topic-based tweet retrieval
# ---------------------------------------------------------------------------
# Retrieval strategy: "llm" (LLM relevance judgment), "topic" (topic-model
# gating), or "none" (raw tweets, equivalent to --skip-retrieval).
RETRIEVAL_METHOD = "llm"

# Cleaned tweet corpus used for topic modelling. Built separately — must
# contain the columns: id, bioguide_id, created_at, text.
# NOTE: deliberately separate from TWEETS_PKL above, which is left untouched.
TWEETS_TOPIC_PKL = DATA_DIR / "tweets_full.pkl"

