def load_tweets() -> pd.DataFrame:
    """
    Load the pre-built tweets_full.pkl.

    Relevant columns: id, author_id, created_at, text, handle, bioguide_id
    """
    logger.info("Loading tweets from %s …", config.TWEETS_PKL)
    df = pd.read_pickle(config.TWEETS_PKL)

    df["created_at"] = pd.to_datetime(df["created_at"], utc=True, errors="coerce")
    df["created_at"] = df["created_at"].dt.tz_localize(None)  # strip tz → naive UTC
    df.dropna(subset=["created_at"], inplace=True)
    df["handle"] = df["handle"].str.lower().str.strip()

    n_with_bio = df["bioguide_id"].notna().sum() if "bioguide_id" in df.columns else 0
    logger.info(
        "Loaded %d tweets from %d unique handles — %d (%.1f%%) have a bioguide_id.",
        len(df), df["handle"].nunique(),
        n_with_bio, n_with_bio / len(df) * 100 if len(df) else 0,
    )
    return df


def build_tweet_index(tweets_df: pd.DataFrame) -> Dict[str, pd.DataFrame]:
    """
    Build a bioguide -> DataFrame index from the tweets DataFrame.

    Relies on the ``bioguide_id`` column added to tweets_full.pkl by the
    notebook cell that maps twitter identifiers to bioguide IDs.  Tweets
    without a bioguide_id are silently excluded from the index (they cannot
    be linked to any member in the votes data).

    Returns
    -------
    dict[str, pd.DataFrame]
        Keys are bioguide strings; values are DataFrames containing at least
        ``created_at`` and ``text`` columns, sorted by ``created_at``
        descending so the most recent tweet comes first.
    """
    if "bioguide_id" not in tweets_df.columns:
        logger.error(
            "tweets_df has no 'bioguide_id' column.  "
            "Re-run the mapping notebook cell and rebuild tweets_full.pkl."
        )
        return {}

    mapped = tweets_df.dropna(subset=["bioguide_id"]).copy()
    mapped["bioguide_id"] = mapped["bioguide_id"].astype(str)

    index: Dict[str, pd.DataFrame] = {}
    for bioguide, group in mapped.groupby("bioguide_id", sort=False):
        index[bioguide] = (
            group.sort_values("created_at", ascending=False)
                 .reset_index(drop=True)
        )

    logger.info(
        "Tweet index built: %d members with at least one tweet "
        "(%d tweets total, %d tweets excluded — no bioguide_id).",
        len(index),
        len(mapped),
        len(tweets_df) - len(mapped),
    )
    return index


def log_coverage(votes_df: pd.DataFrame, tweet_index: Dict[str, pd.DataFrame]) -> None:
    """Log what fraction of members in the vote data have tweet coverage."""
    vote_members  = set(votes_df["bioguide"].dropna().unique())
    tweet_members = set(tweet_index.keys())
    covered   = vote_members & tweet_members
    uncovered = vote_members - tweet_members
    logger.info(
        "Tweet coverage: %d/%d members in vote data have tweets (%.1f%%). "
        "%d members will be predicted on past votes + party only.",
        len(covered), len(vote_members),
        len(covered) / len(vote_members) * 100 if vote_members else 0,
        len(uncovered),
    )


def save_member_splits(votes_df: pd.DataFrame, tweet_index: Dict[str, pd.DataFrame]) -> None:
    """
    Build per-member DataFrames and save covered / uncovered groups as pkl.

    One row per unique bioguide with columns:
        bioguide, member_name, party, state, chamber
    """
    member_rows = (
        votes_df.sort_values("vote_date", ascending=False)
        .drop_duplicates(subset=["bioguide"])
    )
    members = member_rows[["bioguide", "member_name", "party", "state", "chamber"]].copy()

    tweet_members = set(tweet_index.keys())
    covered   = members[members["bioguide"].isin(tweet_members)].reset_index(drop=True)
    uncovered = members[~members["bioguide"].isin(tweet_members)].reset_index(drop=True)

    covered.to_pickle(config.MEMBERS_WITH_TWEETS_PKL)
    uncovered.to_pickle(config.MEMBERS_WITHOUT_TWEETS_PKL)

    logger.info(
        "Saved member splits: %d with tweets → %s, %d without → %s",
        len(covered), config.MEMBERS_WITH_TWEETS_PKL.name,
        len(uncovered), config.MEMBERS_WITHOUT_TWEETS_PKL.name,
    )


def filter_to_covered(votes_df: pd.DataFrame, tweet_index: Dict[str, pd.DataFrame]) -> pd.DataFrame:
    """Return votes_df filtered to only members that appear in tweet_index."""
    covered_bioguides = set(tweet_index.keys())
    before = len(votes_df)
    filtered = votes_df[votes_df["bioguide"].isin(covered_bioguides)].copy()
    logger.info(
        "Filtered votes to covered members: %d → %d rows (%.1f%% kept).",
        before, len(filtered), len(filtered) / before * 100 if before else 0,
    )
    return filtered
