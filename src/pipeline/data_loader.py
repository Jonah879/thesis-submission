"""
data_loader.py — Loads and normalises all raw data sources.

Vote data is loaded from pre-processed CSVs (generated by preprocess_votes.py).
Run that script once before using the pipeline.

Public API:
    load_votes(chamber="both")               -> pd.DataFrame
    load_tweets()                            -> pd.DataFrame
    build_tweet_index(tweets_df)             -> dict[bioguide -> pd.DataFrame]
"""

