def load_votes(chamber: Literal["house", "senate", "both"] = "both") -> pd.DataFrame:
    """
    Load the pre-processed per-member vote CSVs produced by preprocess_votes.py.

    Columns: vote_id, vote_date, bill_number, bill_title, question,
             congress, session, bioguide, member_name, party, state,
             vote_cast, [lis_member_id — senate only]
    """
    dfs = []

    if chamber in ("house", "both"):
        if not config.HOUSE_MEMBERS_CSV.exists():
            raise FileNotFoundError(
                f"House votes CSV not found: {config.HOUSE_MEMBERS_CSV}\n"
                "Run:  python preprocess_votes.py"
            )
        logger.info("Loading house votes from %s …", config.HOUSE_MEMBERS_CSV.name)
        df = pd.read_csv(config.HOUSE_MEMBERS_CSV, parse_dates=["vote_date"], low_memory=False)
        dfs.append(df)
        logger.info("  → %d house member-vote rows.", len(df))

    if chamber in ("senate", "both"):
        if not config.SENATE_MEMBERS_CSV.exists():
            raise FileNotFoundError(
                f"Senate votes CSV not found: {config.SENATE_MEMBERS_CSV}\n"
                "Run:  python preprocess_votes.py"
            )
        logger.info("Loading senate votes from %s …", config.SENATE_MEMBERS_CSV.name)
        df = pd.read_csv(config.SENATE_MEMBERS_CSV, parse_dates=["vote_date"], low_memory=False)
        dfs.append(df)
        logger.info("  → %d senate member-vote rows.", len(df))

    combined = pd.concat(dfs, ignore_index=True)

    # Drop rows with no bioguide — can't link to tweets or past votes
    before = len(combined)
    combined.dropna(subset=["bioguide"], inplace=True)
    dropped = before - len(combined)
    if dropped:
        logger.warning("Dropped %d rows with no bioguide (%.1f%%).", dropped, dropped / before * 100)

    # Exclude "Not Voting" rows — pipeline only predicts Yea/Nay
    before = len(combined)
    combined = combined[combined["vote_cast"].isin(["Yea", "Nay"])].copy()
    logger.info("Excluded non-Yea/Nay votes: %d -> %d rows", before, len(combined))

    # # --- TEMP: restrict to votes on/after June 2024 for testing ---
    # cutoff = pd.Timestamp("2024-06-01")
    # before = len(combined)
    # combined = combined[combined["vote_date"] >= cutoff].copy()
    # logger.info("Filtered to votes >= %s: %d -> %d rows", cutoff.date(), before, len(combined))

    combined.sort_values("vote_date", inplace=True)
    combined.reset_index(drop=True, inplace=True)

    logger.info(
        "Loaded %d total member-vote rows | %d unique members | %d unique votes.",
        len(combined), combined["bioguide"].nunique(), combined["vote_id"].nunique(),
    )

    # Attach bill summaries (see bill_summaries_data.py) keyed by vote_id.
    summaries = load_bill_summaries()
    combined["bill_summary"] = combined["vote_id"].map(summaries).fillna("")
    combined["has_bill_summary"] = combined["bill_summary"].str.strip() != ""
    n_votes = combined["vote_id"].nunique()
    n_votes_with_summary = combined.loc[combined["has_bill_summary"], "vote_id"].nunique()
    logger.info(
        "Bill summary coverage: %d/%d unique votes have a summary (%.1f%%).",
        n_votes_with_summary, n_votes,
        n_votes_with_summary / n_votes * 100 if n_votes else 0,
    )

    return combined


def _truncate_words(text: str, max_words: int) -> str:
    """Truncate text to at most max_words words (whitespace-split)."""
    words = text.split()
    if len(words) <= max_words:
        return text
    return " ".join(words[:max_words]) + " …"


def load_bill_summaries() -> Dict[str, str]:
    """
    Load the congress.gov bill summary lookup CSVs (one row per vote_id,
    produced by data/bill_summaries_data.py) and return a vote_id -> summary
    text mapping. Votes with no resolvable bill or no summary map to "".

    Summaries longer than config.MAX_SUMMARY_WORDS are truncated.
    """
    summaries: Dict[str, str] = {}
    n_total = 0
    n_truncated = 0

    for path in (config.HOUSE_BILL_SUMMARIES_CSV, config.SENATE_BILL_SUMMARIES_CSV):
        if not path.exists():
            logger.warning(
                "Bill summaries CSV not found: %s — bill_summary will be empty "
                "for these votes. Run: python data/bill_summaries_data.py",
                path,
            )
            continue
        df = pd.read_csv(path, usecols=["vote_id", "summary_text"])
        for vote_id, text in zip(df["vote_id"], df["summary_text"]):
            if not isinstance(text, str) or not text:
                summaries[vote_id] = ""
                continue
            n_total += 1
            truncated = _truncate_words(text, config.MAX_SUMMARY_WORDS)
            if truncated != text:
                n_truncated += 1
            summaries[vote_id] = truncated

    if n_total:
        logger.info(
            "Bill summaries: %d/%d exceeded %d words and were truncated.",
            n_truncated, n_total, config.MAX_SUMMARY_WORDS,
        )

    return summaries


def save_loaded_votes(votes_df: pd.DataFrame) -> None:
    """Save the loaded votes DataFrame to CSV for post-hoc inspection."""
    votes_df.to_csv(config.LOADED_VOTES_CSV, index=False)
    logger.info("Saved loaded votes to %s (%d rows).", config.LOADED_VOTES_CSV.name, len(votes_df))


